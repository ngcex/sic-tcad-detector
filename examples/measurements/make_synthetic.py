"""Write the SYNTHETIC example measurement files of examples/measurements/data/.

Every number in these files is computed by the ETNA model itself (no measurement, no
typed value): they show the requested formats end to end and let the loaders and the
comparison/inversion functions be checked on a known truth (``roundtrip.py``,
tests/test_measurement_examples.py). Each file says SYNTHETIC in its metadata.

Truth device: ``measured_cv_tabulated_config()`` (the 19-knot measured-C-V preset,
4 mm^2 dosimeter stack). Files:

- ``cv_synthetic.csv``: C-V 0 .. -200 V every 2 V (the range requested from the
  foundry/INFN-LNS), C in pF, a 0.3 % 1-sigma column, 100 kHz / 300 K metadata.
- ``sims_synthetic.csv``: N and Al depth profile from the surface (p+ Al, the junction,
  the epi donor table, the n+), every 50 nm to 12 um, 10 % relative sigma and an
  idealised 1e13 cm^-3 N detection limit (values below it written as 0).
- ``it_synthetic.csv``: dark current at -10 and -50 V, 300 .. 380 K every 20 K, pA.

    uv run python examples/measurements/make_synthetic.py
"""

from __future__ import annotations

from pathlib import Path

import numpy as np

import etna
from etna.api.device import measured_cv_tabulated_config
from etna.measurements import model_current_vs_T, model_donor_profile

OUT = Path(__file__).resolve().parent / "data"
NOTE = "# notes: SYNTHETIC example generated by examples/measurements/make_synthetic.py from the ETNA model (measured_cv_tabulated_config); NOT a measurement"
# N detection limit written into the synthetic SIMS file. Deliberately LOW (an idealised
# technique) so the round trip can rebuild the epi; a real SIMS N floor in SiC may sit
# above a 1e13-1e14 epi, and then the loader flags those knots as censored and
# ProfileTable.to_device_config refuses them (tests/test_measurement_examples.py).
N_DL = 1e13


def g(v) -> str:
    return f"{float(v):.10g}"


def truth():
    return measured_cv_tabulated_config()


def cv_file(cfg) -> str:
    r = etna.run_cv(cfg, 0.0, -200.0, 101)
    if r.metadata.get("truncated"):
        raise RuntimeError("model C-V truncated before -200 V")
    lines = [
        "# ETNA C-V example (see data/measurements/README.md for the format)",
        NOTE,
        "# sample: synthetic-dosimeter-01",
        "# device: 2x2 mm2 p+/n- pad (model)",
        "# instrument: none (model)",
        f"# area_cm2: {g(cfg.area_cm2)}",
        "# frequency_hz: 100000",
        f"# temperature_k: {g(cfg.T)}",
        "# bias_convention: reverse_negative",
        "V_V,C_pF,sigma_C_pF",
    ]
    for v, c in zip(r.x, r.y):
        lines.append(f"{g(v)},{g(c * 1e12)},{g(c * 1e12 * 0.003)}")
    return "\n".join(lines) + "\n"


def sims_file(cfg) -> str:
    xj = float(cfg.substrate_thickness_um)  # p+ thickness = junction depth (model)
    depth = np.round(np.arange(0.0, 12.0 + 1e-9, 0.05), 6)
    below = depth - xj
    N = np.where(below >= 0, model_donor_profile(cfg, np.maximum(below, 0.0)), 0.0)
    N = np.where(N >= N_DL, N, 0.0)  # below the detection limit -> 0
    Al = np.where(depth <= xj, cfg.N_A, 0.0)
    lines = [
        "# ETNA SIMS example (see data/measurements/README.md for the format)",
        NOTE,
        "# technique: SIMS",
        "# quantity: total N and Al atoms (model donor/acceptor profile)",
        "# depth_reference: surface",
        f"# junction_depth_um: {g(xj)}",
        f"# detection_limit_N_cm3: {g(N_DL)}",
        "# rel_sigma_N: 0.1",
        "# rel_sigma_Al: 0.1",
        "# sample: synthetic-dosimeter-01",
        "depth_um,N_cm3,Al_cm3",
    ]
    for d, n, a in zip(depth, N, Al):
        lines.append(f"{g(d)},{g(n)},{g(a)}")
    return "\n".join(lines) + "\n"


def it_file(cfg) -> str:
    T = np.arange(300.0, 380.0 + 1e-9, 20.0)
    lines = [
        "# ETNA I(T) example (see data/measurements/README.md for the format)",
        NOTE,
        "# sample: synthetic-dosimeter-01",
        f"# area_cm2: {g(cfg.area_cm2)}",
        "# bias_convention: reverse_negative",
        "V_V,T_K,I_pA,sigma_I_pA",
    ]
    for V in (-10.0, -50.0):
        I, _ = model_current_vs_T(cfg, T, V)
        for t, i in zip(T, I):
            lines.append(f"{g(V)},{g(t)},{g(-i * 1e12)},{g(i * 1e12 * 0.02)}")
    return "\n".join(lines) + "\n"


def build() -> dict:
    cfg = truth()
    return {
        "cv_synthetic.csv": cv_file(cfg),
        "sims_synthetic.csv": sims_file(cfg),
        "it_synthetic.csv": it_file(cfg),
    }


def main():
    OUT.mkdir(exist_ok=True)
    for name, text in build().items():
        (OUT / name).write_text(text)
        print(f"wrote {name} ({text.count(chr(10))} lines)")


if __name__ == "__main__":
    main()
