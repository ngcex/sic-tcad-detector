class TestDevsimParity:
    def test_guard_ring_scan_and_sharing(self, gr_solver):
        s = gr_solver
        it, du = s.dark_check_result
        assert it <= 3 and du < 1e-12  # flat-quasi-Fermi dark state is the DD state
        assert _psi_err(s, "gr") < 1e-10
        info = s.mesh.info
        ns = cut_node_sets(s.mesh, info["sv_half_width_cm"] + 0.5 * info["gap_cm"])
        sc = cce_lateral_scan_fv2d(
            s, contact="anode", node_sets=ns, x_positions_cm=REF["gr"]["x_cm"]
        )
        assert np.max(np.abs(sc["cce_values"] - REF["gr"]["cce_anode"])) < 1e-10
        assert np.max(np.abs(sc["residuals"])) < 1e-12  # 3 contacts conserve current
        assert np.max(sc["direct_mismatch"]) < 1e-4
        row = REF["gr"]["sharing"][1]
        fr, res = contact_sharing_fv2d(
            s, alpha_stripe_generation_fv2d(s.mesh, row["x_um"] * 1e-4), ns
        )
        for c in fr:
            assert abs(fr[c] - row[c]) < 1e-10, c
        assert abs(res) < 1e-12

    def test_guard_ring_needs_node_sets(self, gr_solver):
        s = gr_solver
        G = s.order.flat(alpha_stripe_generation_fv2d(s.mesh, 0.0))
        (st,), (Gf,) = s.solve_generation(G[None])
        with pytest.raises(ValueError, match="shares its majority carrier"):
            s.contact_currents(st, Gf)
        assert "cathode" in s.contact_currents(st, Gf, only=("cathode",))

    def test_gummel_band_and_superlu_agree(self, gr_solver):
        s = gr_solver
        G = alpha_stripe_generation_fv2d(s.mesh, 49e-4)
        out = []
        for kind in ("band", "superlu"):
            s.gummel_solver = kind
            (st,), (Gf,) = s.solve_generation(G[None])
            out.append(s.contact_currents(st, Gf, only=("cathode",))["cathode"])
        s.gummel_solver = "auto"
        assert abs(out[0] / out[1] - 1) < 1e-11

    def test_3d_electrode_axisymmetric(self):
        from etna.core.alternative_structures import create_3d_electrode_device

        mesh, _ = mesh_from_builder(create_3d_electrode_device)
        assert mesh.coordinate_system == "cylindrical"
        ref = REF["elec"]
        s = prepared_solver(mesh, {"cathode": ref["V"]})
        assert _psi_err(s, "elec") < 1e-9
        for c, key in (("cathode", "cce_cathode"), ("anode", "cce_anode")):
            sc = cce_lateral_scan_fv2d(s, contact=c, x_positions_cm=ref["r_cm"])
            assert np.max(np.abs(sc["cce_values"] - ref[key])) < 1e-9, c

    def test_mesa(self):
        from etna.core.alternative_structures import create_mesa_device

        mesh, _ = mesh_from_builder(create_mesa_device, depth_mesh="legacy")
        s = prepared_solver(mesh, {"cathode": REF["mesa"]["V"]})
        assert _psi_err(s, "mesa") < 1e-10
        sc = cce_lateral_scan_fv2d(s, n_points=len(REF["mesa"]["cce"]))
        assert np.max(np.abs(sc["cce_values"] - REF["mesa"]["cce"])) < 1e-10


def test_cross_engine_parity_with_engine2d():
    """Default (n+) laterally uniform diode: fv2d on devsim's mesh == engine2d."""
    from etna.core.device2d import create_sic_2d_device
    from etna.core.engine2d import lateral_cce_scan_2d

    hw, V, n = 25.0, 20.0, 4
    e2 = lateral_cce_scan_2d(hw, V, n_lateral_points=n)
    mesh, _ = mesh_from_builder(create_sic_2d_device, half_width_um=hw)
    s = prepared_solver(mesh, {"cathode": V})
    sc = cce_lateral_scan_fv2d(s, n_points=n)
    assert np.max(np.abs(sc["cce_values"] - e2["cce_values"])) < 1e-9


def test_cce_lateral_scan_engine_switch():
    """charge_collection_2d.cce_lateral_scan(engine="fv2d") on a devsim-biased device."""
    import devsim

    from etna.core.alternative_structures import create_mesa_device
    from etna.core.charge_collection_2d import cce_lateral_scan
    from etna.core.drift_diffusion import ramp_bias, setup_sic_drift_diffusion
    from etna.core.poisson import setup_poisson, solve_equilibrium

    info = create_mesa_device(device_name="fv2d_switch", pillar_half_width_um=10.0)
    try:
        setup_poisson(info)
        solve_equilibrium(info)
        setup_sic_drift_diffusion(info)
        ramp_bias(info, V_target=4.0, contact="cathode", V_step=1.0, V_step_max=2.0)
        ref = cce_lateral_scan(info, n_points=3)
        fv = cce_lateral_scan(info, n_points=3, engine="fv2d")
        with pytest.raises(ValueError):
            cce_lateral_scan(info, n_points=3, engine="gpu")
    finally:
        devsim.delete_device(device=info["device_name"])
    # devsim's DC solve stops at its own tolerance (rel 1e-10 tier): parity to 1e-8
    assert np.max(np.abs(fv["cce_values"] - ref["cce_values"])) < 1e-8
    assert set(ref) <= set(fv)


