@pytest.mark.parametrize(
    "builder_name,struct,kw",
    [
        ("create_guard_ring_device", guard_ring_structure, {}),
        (
            "create_guard_ring_device",
            guard_ring_structure,
            {"lateral_straggle_cm": 2e-5},
        ),
        ("create_mesa_device", mesa_structure, {}),
        ("create_3d_electrode_device", electrode3d_structure, {}),
    ],
)
def test_native_structures_reproduce_devsim_doping(builder_name, struct, kw):
    from etna.core import alternative_structures as A

    dm, _ = mesh_from_builder(getattr(A, builder_name), **kw)
    nm = build_mesh(struct(**kw), dm.xs, dm.ys)
    for f in ("donors", "acceptors", "mun_h", "mun_v", "mup_h", "mup_v"):
        a, b = getattr(dm, f), getattr(nm, f)
        assert np.max(np.abs(a - b) / np.maximum(np.abs(a), 1e-300)) < 1e-14, f
    assert np.max(np.abs(dm.net - nm.net) / np.maximum(np.abs(dm.net), 1.0)) < 1e-13
    assert set(dm.contacts) == set(nm.contacts)
    for c in dm.contacts:
        assert np.array_equal(dm.contacts[c], nm.contacts[c]), c


