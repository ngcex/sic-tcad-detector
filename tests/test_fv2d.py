def _psi_err(s, tag):
    m = s.mesh
    i = np.searchsorted(m.xs, PSI[f"{tag}_x"])
    j = np.searchsorted(m.ys, PSI[f"{tag}_y"])
    return np.max(np.abs(s.potential()[j, i] - PSI[f"{tag}_psi"]))


