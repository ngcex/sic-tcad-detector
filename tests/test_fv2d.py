def _info(T=300.0):
    from etna.core.sic_material import SiC4H_Parameters, intrinsic_concentration

    return dict(T=T, n_i=intrinsic_concentration(T, SiC4H_Parameters())[0])


def _undoped_mesh(xs, ys, cs, left, right):
    """Charge-free (D = 0) mesh with two Dirichlet columns: a Laplace problem."""
    ny, nx = len(ys), len(xs)
    vol, gh, gv = box_geometry(xs, ys, cs)
    z = np.zeros((ny, nx))
    c1 = np.zeros((ny, nx), bool)
    c1[:, 0] = True
    c2 = np.zeros((ny, nx), bool)
    c2[:, -1] = True
    mu_h, mu_v = np.full((ny, nx - 1), 100.0), np.full((ny - 1, nx), 100.0)
    return FVMesh(
        xs=xs, ys=ys, vol=vol, gh=gh, gv=gv, donors=z, acceptors=z, net=z,
        mun_h=mu_h, mun_v=mu_v, mup_h=mu_h, mup_v=mu_v,
        contacts={left: c1, right: c2}, coordinate_system=cs, info=_info(),
    )  # fmt: skip


# ----------------------------------------------------------------- analytic
class TestAnalytic:
    def test_coaxial_laplace(self):
        """(r, z) Laplace between coaxial electrodes a < r < b: psi = V ln(b/r) / ln(b/a).
        Exact on a geometric r mesh (constant discrete flux 2 pi r_mid du / h), second
        order on a uniform one."""

        def err(xs, a, b, V=3.0):
            m = _undoped_mesh(xs, np.linspace(0, 1e-4, 4), "cylindrical", "in", "out")
            s = Solver2D(m).equilibrium().set_bias({"in": V})
            d = (
                s.potential()[1] - s.potential()[1, -1]
            )  # equal built-in offsets of D = 0
            return np.max(np.abs(d - V * np.log(b / xs) / np.log(b / a)))

        a, b = 5e-4, 50e-4
        assert err(np.geomspace(a, b, 21), a, b) < 1e-13
        errs = [err(np.linspace(a, b, n), a, b) for n in (21, 41, 81)]
        order = np.log2(np.array(errs[:-1]) / np.array(errs[1:]))
        assert errs[-1] < 1e-3 and np.all(order > 1.8), (errs, order)

    def test_cartesian_plate_exact(self):
        """Cartesian Laplace between plates is linear: the box scheme is exact."""
        xs = np.sort(np.r_[0, np.random.default_rng(1).uniform(0, 1e-3, 30), 1e-3])
        m = _undoped_mesh(xs, np.linspace(0, 2e-4, 5), "cartesian", "a", "b")
        s = Solver2D(m).equilibrium().set_bias({"a": 2.0})
        d = s.potential()[2] - s.potential()[2, -1]
        assert np.max(np.abs(d - 2.0 * (1 - xs / 1e-3))) < 1e-12

    def test_cylindrical_box_geometry_matches_devsim_couplings(self):
        from etna.core.alternative_structures import create_3d_electrode_device

        dm, _ = mesh_from_builder(create_3d_electrode_device)
        vol, gh, gv = box_geometry(dm.xs, dm.ys, "cylindrical")
        assert np.max(np.abs(gh / dm.gh - 1)) < 1e-12
        assert np.max(np.abs(gv / dm.gv - 1)) < 1e-11
        # devsim's CylindricalNodeVolume is assembled per triangle: not the exact ring
        r = vol / dm.vol
        assert 0.59 < r.min() < 0.61 and abs(np.median(r) - 1) < 2e-3


class TestOrdering:
    def test_short_dimension_fastest_roundtrip(self):
        A = np.arange(12.0).reshape(3, 4)  # ny 3, nx 4 -> transpose (y fastest)
        o = SolverOrder(4, 3, True)
        assert o.m == 3 and o.ns == 4
        assert np.array_equal(o.grid(o.flat(A)), A)
        ef, es = o.edges(np.ones((3, 3)), 2 * np.ones((2, 4)))
        assert ef.shape == (4, 2) and es.shape == (3, 3) and ef[0, 0] == 2

    def test_mesh_validation(self):
        xs, ys = np.linspace(0, 1, 4), np.linspace(0, 1, 3)
        with pytest.raises(ValueError):
            _undoped_mesh(xs, ys, "spherical", "a", "b")


