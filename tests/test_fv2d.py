def test_graded_lines_hit_knots_and_grade():
    xs = graded_lines([(0, 1e-5), (1e-3, 1e-7), (2e-3, 1e-5)], 0, 2e-3, ratio=1.2)
    assert (
        xs[0] == 0
        and xs[-1] == 2e-3
        and np.any(np.isclose(xs, 1e-3, rtol=0, atol=1e-18))
    )
    h = np.diff(xs)
    assert (
        h.min() < 2e-7 and np.max(h[1:] / h[:-1]) < 1.6 and np.max(h[:-1] / h[1:]) < 1.6
    )


def test_adaptive_refinement_contact_cell_convergence():
    """The CCE of the contact-on-epi cathode converges at first order in the contact cell
    (LOG.md); the contact rule makes successive differences contract."""
    st = mesa_structure(pillar_half_width_um=5.0, depth_mesh="legacy")
    r = adaptive_cce_scan(
        st, {"cathode": 10.0}, dict(x_positions_cm=[0.0]), tol=1e-12, max_levels=4
    )
    d = [L["dcce"] for L in r["levels"][1:]]
    assert len(d) == 3 and d[2] < 0.5 * d[0]
    c = [L["cce"][0] for L in r["levels"]]
    assert c[-1] < c[0] - 3e-3  # coarse contact cell overestimates the CCE
    assert np.isfinite(r["error_estimate"])


def test_scan_result_feeds_mc_coupling():
    from etna.core.mc_coupling import lateral_cce_factor

    st = guard_ring_structure(sv_half_width_um=10.0)
    s = prepared_solver(build_mesh(st), {"cathode": 5.0}, dark_check=False)
    ns = cut_node_sets(s.mesh, st.info["sv_half_width_cm"] + 0.5 * st.info["gap_cm"])
    sc = cce_lateral_scan_fv2d(
        s,
        n_points=5,
        contact="anode",
        node_sets=ns,
        x_max_cm=st.info["sv_half_width_cm"],
    )
    f, n_out = lateral_cce_factor(np.array([0.0, 5e-4, 2e-3]), sc)
    assert f[0] == pytest.approx(1.0) and f[1] <= 1.0 and n_out == 1
    assert sc["edge_to_center_ratio"] < 1.0  # the SV edge loses charge to the guard
